"""Copies Mixxx track metadata (ratings, cues/hotcues, play counts, beatgrid,
key, comments, crate memberships, ...) from one mixxxdb.sqlite to another.

The two sticks/instances have different absolute file paths, so tracks are
matched by filename + duration instead (see match_tracks). Ambiguous matches
(same filename, no duration match) are left unmatched and reported rather
than guessed at -- this writes to a real, hand-curated DJ library, and a
wrong guess here is worse than a skipped track.

Schema reference (Mixxx's res/schema.xml, tables: library, track_locations,
cues, crates, crate_tracks): library.location is an integer FK that equals
track_locations.id (despite the confusing column name) -- that's the join
Mixxx itself uses at runtime.
"""
from __future__ import annotations

import logging
import shutil
import sqlite3
from collections import defaultdict
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path

logger = logging.getLogger("spotify_queuer.mixxx_migrate")

# Duration can drift by a fraction of a second between independent analyses
# of "the same" file -- tolerate a little instead of requiring an exact match.
DURATION_TOLERANCE_SECONDS = 1.5

# Copied source -> destination for a matched track. Deliberately excludes
# anything path/file-derived (location, filetype, bitrate, samplerate,
# channels, duration, url) or auto-regenerated by Mixxx on its next scan
# (wavesummaryhex, coverart_*, header_parsed, mixxx_deleted) -- only the
# user's own curation/analysis work travels.
METADATA_COLUMNS = [
    "rating", "color", "comment", "key", "key_id", "keys", "keys_version", "keys_sub_version",
    "bpm", "bpm_lock", "beats", "beats_version", "beats_sub_version",
    "timesplayed", "played", "last_played_at",
    "replaygain", "replaygain_peak",
    "grouping", "composer", "album_artist", "genre", "year", "tracknumber", "tuning_frequency_hz",
]


@dataclass(frozen=True)
class TrackMatch:
    source_track_id: int
    dest_track_id: int
    filename: str


@dataclass
class MigrationReport:
    matched: list[TrackMatch] = field(default_factory=list)
    unmatched_source_filenames: list[str] = field(default_factory=list)
    cues_copied: int = 0
    crate_memberships_copied: int = 0
    crates_created: list[str] = field(default_factory=list)

    @property
    def matched_count(self) -> int:
        return len(self.matched)


def backup_database(db_path: Path | str) -> Path:
    db_path = Path(db_path)
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    backup_path = db_path.with_name(f"{db_path.name}.bak-{timestamp}")
    shutil.copy2(db_path, backup_path)
    return backup_path


def _fetch_tracks(conn: sqlite3.Connection, schema: str) -> list[tuple[int, str, float | None]]:
    """schema is "src." or "" (the attached source db, or the destination's
    own main schema) -- a fixed internal constant, never user input, so
    f-string interpolation into the identifier position is safe here."""
    lib, loc = f"{schema}library", f"{schema}track_locations"
    rows = conn.execute(
        f"""
        SELECT {lib}.id, {loc}.filename, {lib}.duration
        FROM {lib} JOIN {loc} ON {lib}.location = {loc}.id
        WHERE {lib}.mixxx_deleted IS NOT 1
        """
    ).fetchall()
    return [(r[0], r[1], r[2]) for r in rows]


def match_tracks(
    source_tracks: list[tuple[int, str, float | None]],
    dest_tracks: list[tuple[int, str, float | None]],
) -> tuple[list[TrackMatch], list[str]]:
    dest_by_filename: dict[str, list[tuple[int, float | None]]] = defaultdict(list)
    for dest_id, filename, duration in dest_tracks:
        dest_by_filename[filename].append((dest_id, duration))

    matches: list[TrackMatch] = []
    unmatched: list[str] = []
    for src_id, filename, src_duration in source_tracks:
        candidates = dest_by_filename.get(filename, [])
        if len(candidates) == 1:
            matches.append(TrackMatch(src_id, candidates[0][0], filename))
            continue
        if len(candidates) > 1:
            scored = [
                (abs(src_duration - dest_duration), dest_id)
                for dest_id, dest_duration in candidates
                if src_duration is not None and dest_duration is not None
            ]
            scored = [s for s in scored if s[0] <= DURATION_TOLERANCE_SECONDS]
            if len(scored) == 1:
                matches.append(TrackMatch(src_id, scored[0][1], filename))
                continue
        unmatched.append(filename)  # no candidate, or an ambiguous one -- leave for manual review
    return matches, unmatched


def _copy_metadata(conn: sqlite3.Connection, match: TrackMatch) -> None:
    set_clause = ", ".join(f"{col} = (SELECT {col} FROM src.library WHERE id = :src_id)" for col in METADATA_COLUMNS)
    conn.execute(f"UPDATE library SET {set_clause} WHERE id = :dest_id", {"src_id": match.source_track_id, "dest_id": match.dest_track_id})


def _copy_cues(conn: sqlite3.Connection, match: TrackMatch) -> int:
    """Replaces the destination track's cues with the source's -- so re-running
    a migration doesn't pile up duplicate hot cues on the destination."""
    conn.execute("DELETE FROM cues WHERE track_id = ?", (match.dest_track_id,))
    cur = conn.execute(
        """
        INSERT INTO cues (track_id, type, position, length, hotcue, label, color)
        SELECT ?, type, position, length, hotcue, label, color FROM src.cues WHERE track_id = ?
        """,
        (match.dest_track_id, match.source_track_id),
    )
    return cur.rowcount


def _ensure_crate(conn: sqlite3.Connection, name: str, created: list[str]) -> int:
    row = conn.execute("SELECT id FROM crates WHERE name = ?", (name,)).fetchone()
    if row is not None:
        return row[0]
    cur = conn.execute("INSERT INTO crates (name, count, show, locked, autodj_source) VALUES (?, 0, 1, 0, 0)", (name,))
    created.append(name)
    return cur.lastrowid


def _copy_crate_memberships(conn: sqlite3.Connection, match: TrackMatch, report: MigrationReport) -> None:
    rows = conn.execute(
        """
        SELECT src.crates.name FROM src.crate_tracks
        JOIN src.crates ON src.crate_tracks.crate_id = src.crates.id
        WHERE src.crate_tracks.track_id = ?
        """,
        (match.source_track_id,),
    ).fetchall()
    for (name,) in rows:
        dest_crate_id = _ensure_crate(conn, name, report.crates_created)
        cur = conn.execute("INSERT OR IGNORE INTO crate_tracks (crate_id, track_id) VALUES (?, ?)", (dest_crate_id, match.dest_track_id))
        if cur.rowcount:
            report.crate_memberships_copied += 1


def migrate(source_db_path: Path | str, dest_db_path: Path | str, dry_run: bool = False) -> MigrationReport:
    """Backs up dest_db_path (unless dry_run), then migrates matched tracks'
    metadata, cues and crate memberships from source_db_path into it, all in
    one transaction -- any failure rolls back to exactly the pre-migration
    state, on top of the standalone file backup."""
    source_db_path, dest_db_path = Path(source_db_path), Path(dest_db_path)
    report = MigrationReport()

    if not dry_run:
        backup_path = backup_database(dest_db_path)
        logger.info("Backed up destination database to %s before migrating", backup_path)

    conn = sqlite3.connect(str(dest_db_path))
    try:
        conn.execute("ATTACH DATABASE ? AS src", (str(source_db_path),))

        matches, unmatched = match_tracks(_fetch_tracks(conn, "src."), _fetch_tracks(conn, ""))
        report.matched, report.unmatched_source_filenames = matches, unmatched

        for match in matches:
            _copy_metadata(conn, match)
            report.cues_copied += _copy_cues(conn, match)
            _copy_crate_memberships(conn, match, report)

        conn.execute("UPDATE crates SET count = (SELECT COUNT(*) FROM crate_tracks WHERE crate_tracks.crate_id = crates.id)")

        if dry_run:
            conn.rollback()
        else:
            conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()

    return report
